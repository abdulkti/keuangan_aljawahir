    public function importBackup()
    {
        $redirect = $this->redirectIfNotRole(['superadmin']);
        if ($redirect) return $redirect;

        if (($this->userData['sekolah'] ?? 'admin') !== 'admin') {
            return redirect()->back()->with('error', 'Hanya admin yang bisa restore backup.');
        }

        $file = $this->request->getFile('file_backup');
        if (!$file || !$file->isValid()) {
            return redirect()->back()->with('error', 'Pilih file backup terlebih dahulu.');
        }

        $ext = $file->getExtension();
        if (!in_array($ext, ['xlsx', 'xls'])) {
            return redirect()->back()->with('error', 'Format file harus .xlsx atau .xls.');
        }

        try {
            $reader = \PhpOffice\PhpSpreadsheet\IOFactory::createReader(ucfirst($ext));
            $reader->setReadDataOnly(true);
            $spreadsheet = $reader->load($file->getTempName());
        } catch (\Exception $e) {
            return redirect()->back()->with('error', 'Gagal membaca file: ' . $e->getMessage());
        }

        $db = \Config\Database::connect();
        $db->transBegin();
        try {
            $db->query('SET CONSTRAINTS ALL DISABLED');

            // Table order: classes → students → teachers → bills → bill_payments → savings_accounts → savings_transactions → users → academic_years → settings
            $sheetMap = [
                'Kelas'             => 'tb_kelas',
                'Siswa'             => 'tb_siswa',
                'Guru'              => 'tb_guru',
                'Tagihan'           => 'tb_tagihan_siswa',
                'Pembayaran'        => 'tb_pembayaran',
                'Tabungan'          => 'tb_tabungan',
                'Transaksi Tabungan' => 'tb_transaksi_tabungan',
                'Pengguna'          => 'tb_users',
                'Tahun Ajaran'      => 'tb_tahun_ajaran',
                'Pengaturan'        => 'tb_pengaturan',
            ];

            // Truncate existing data (reverse order)
            foreach (array_reverse($sheetMap) as $table) {
                $db->table($table)->truncate();
            }

            // Get actual column names for each table (to filter out extra export columns)
            $tableColumns = [];
            $colResult = $db->query('SELECT TABLE_NAME, COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE table_schema = current_schema()');
            foreach ($colResult->getResultArray() as $colRow) {
                $tableColumns[$colRow['TABLE_NAME']][] = $colRow['COLUMN_NAME'];
            }

            $tingkatEnum = ['A','B','1','2','3','4','5','6','7','8','9'];

            foreach ($sheetMap as $sheetTitle => $table) {
                $sheet = $spreadsheet->getSheetByName($sheetTitle);
                if (!$sheet) continue;

                $rows = $sheet->toArray();
                if (count($rows) < 2) continue;

                $columns = $rows[0];
                if (empty(array_filter($columns))) continue;

                // Clean column names (remove BOM, trim)
                $columns = array_map(fn($c) => trim(preg_replace('/[\x00-\x1F\x80-\xFF]/', '', (string)$c)), $columns);

                // Only keep columns that exist in the table
                $validColumns = $tableColumns[$table] ?? [];
                $allowedIndices = [];
                $namaKelasIdx = null;
                foreach ($columns as $i => $col) {
                    if (!empty($col) && in_array($col, $validColumns, true)) {
                        $allowedIndices[] = $i;
                    }
                    if (strtolower(trim($col)) === 'nama_kelas') {
                        $namaKelasIdx = $i;
                    }
                }

                // For Siswa sheet: auto-create classes from nama_kelas before inserting
                if ($table === 'students' && $namaKelasIdx !== null) {
                    $sekolahIdx = null;
                    foreach ($columns as $i => $col) {
                        if (strtolower(trim($col)) === 'sekolah') {
                            $sekolahIdx = $i;
                            break;
                        }
                    }

                    // Collect existing classes
                    $existingClasses = [];
                    $existingResult = $db->query("SELECT nama_kelas, id FROM tb_kelas")->getResultArray();
                    foreach ($existingResult as $ec) {
                        $existingClasses[$ec['nama_kelas']] = $ec['id'];
                    }

                    // Auto-create missing classes — nama_kelas takes priority over kelas_id
                    foreach (array_slice($rows, 1) as $row) {
                        $nk = trim((string)($row[$namaKelasIdx] ?? ''));
                        if (empty($nk)) continue;
                        if (isset($existingClasses[$nk])) continue;

                        $sekolah = 'smp';
                        if ($sekolahIdx !== null) {
                            $sVal = trim((string)($row[$sekolahIdx] ?? ''));
                            if (in_array($sVal, ['ra', 'sd', 'smp'])) $sekolah = $sVal;
                        }

                        $tingkat = 'A';
                        if (preg_match('/^(\d+)-/', $nk, $m)) {
                            $tingkat = $m[1];
                        } elseif (preg_match('/^RA\s+(.+)/i', $nk, $m)) {
                            $tingkat = strtoupper(trim($m[1]));
                        } elseif (preg_match('/^([A-Z])\b/i', $nk, $m)) {
                            $tingkat = strtoupper($m[1]);
                        }
                        if (!in_array($tingkat, $tingkatEnum, true)) {
                            $tingkat = 'A';
                        }

                        $db->table('tb_kelas')->insert([
                            'nama_kelas' => $nk,
                            'tingkat'    => $tingkat,
                            'jurusan'    => null,
                            'sekolah'    => $sekolah,
                            'created_at' => date('Y-m-d H:i:s'),
                        ]);
                        $existingClasses[$nk] = $db->insertID();
                    }
                }

                $insertBatch = [];
                foreach (array_slice($rows, 1) as $row) {
                    $data = [];
                    $hasData = false;
                    foreach ($allowedIndices as $i) {
                        $col = $columns[$i];
                        $val = $row[$i] ?? '';
                        if ($val !== null && $val !== '') $hasData = true;
                        if ($col === 'password' && !empty($val)) {
                            if (!password_get_info($val)['algo']) {
                                $val = password_hash($val, PASSWORD_DEFAULT);
                            }
                        }
                        $data[$col] = $val === '' ? null : $val;
                    }

                    // For Siswa: nama_kelas always overrides kelas_id
                    if ($table === 'students' && $namaKelasIdx !== null) {
                        $nk = trim((string)($row[$namaKelasIdx] ?? ''));
                        if (!empty($nk) && isset($existingClasses[$nk])) {
                            $data['kelas_id'] = $existingClasses[$nk];
                        } elseif (empty($nk) && (!isset($data['kelas_id']) || empty($data['kelas_id']))) {
                            // Fallback: auto-create default class for this unit
                            $unit = $data['sekolah'] ?? 'smp';
                            $unitLabels = ['ra' => 'RA', 'sd' => 'SD', 'smp' => 'SMP'];
                            $defNk = $unitLabels[$unit] . ' A';
                            if (!isset($existingClasses[$defNk])) {
                                $db->table('tb_kelas')->insert([
                                    'nama_kelas' => $defNk,
                                    'tingkat'    => 'A',
                                    'jurusan'    => null,
                                    'sekolah'    => $unit,
                                    'created_at' => date('Y-m-d H:i:s'),
                                ]);
                                $existingClasses[$defNk] = $db->insertID();
                            }
                            $data['kelas_id'] = $existingClasses[$defNk];
                        }
                    }

                    if (!$hasData) continue;
                    $insertBatch[] = $data;
                }

                if (!empty($insertBatch)) {
                    $db->table($table)->insertBatch($insertBatch);
                }
            }

            // Sync bills with student data: update SPP & Daftar Ulang amounts
            $studentsAfter = $db->query("SELECT id, nominal_spp, nominal_awal_tahun FROM tb_siswa")->getResultArray();
            foreach ($studentsAfter as $sa) {
                if (!empty($sa['nominal_spp'])) {
                    $db->query("UPDATE tb_tagihan_siswa SET nominal = ? WHERE siswa_id = ? AND jenis_tagihan = 'SPP Bulanan' AND nominal != ?", [$sa['nominal_spp'], $sa['id'], $sa['nominal_spp']]);
                }
                if (!empty($sa['nominal_awal_tahun'])) {
                    $db->query("UPDATE tb_tagihan_siswa SET nominal = ? WHERE siswa_id = ? AND jenis_tagihan = 'Daftar Ulang' AND nominal != ?", [$sa['nominal_awal_tahun'], $sa['id'], $sa['nominal_awal_tahun']]);
                }
            }

            $db->query('SET CONSTRAINTS ALL ENABLED');
            $db->transCommit();
            return redirect()->to('/pengaturan')->with('success', 'Backup berhasil direstore. Semua data telah diimpor.');
        } catch (\Exception $e) {
            $db->query('SET CONSTRAINTS ALL ENABLED');
            $db->transRollback();
            return redirect()->back()->with('error', 'Gagal restore backup: ' . $e->getMessage());
        }
    }
